"""
Ejercicio 4: Pedir dos números al usuario y hacer todas las operaciones básicas de una calculadora y mostrarlo por pantalla.
"""

numero_1 = int(input("Ingrese el primer número: "))
numero_2 = int(input("Ingrese el segundo número: "))

print("######CALCULADORA######")
print("Suma: "+str(numero_1 + numero_2))
print("Resta: "+str(numero_1 - numero_2))
print("Multiplicación: "+str(numero_1 * numero_2))
print("División: "+str(numero_1 / numero_2))